// Coverage inventory + behavioral-coverage gate.
//
// Enumerates the app's GLOBAL surface — top-level `function NAME()` declarations
// and `window.NAME =` assignments, across every non-vendor, non-generated js
// file — and records, for each name, whether a suite covers it and whether it is
// part of the BEHAVIORAL surface a user can reach.
//
// Why a global surface at all: these are classic scripts, so every top-level
// function is a window property the pages and the worker call by name. That is
// exactly why a silent defect hides here — a renderer written to survive a
// missing element just stops offering a feature rather than throwing.
//
// The tier is the point. "One suite per exported function" over ~330 globals is
// unfinishable, and an unfinishable gate gets switched off. So the MUST-COVER
// set is the behavioral surface — anything a page wires to an event, anything
// the worker calls — and everything else is a helper that is waivable IN BULK,
// each with a reason recorded in coverage-waivers.json. Nothing is skipped by
// accident; only by a decision someone wrote down.
//
// Coverage is EXECUTION-based, not source-text: the tool runs every suite once
// under V8's coverage collector and a name counts as covered only when a suite
// actually ran its function (see the coverage section below). That is why both
// invocations below run the suites (~10-15s) rather than scanning their text.
//
//   node tools/build-coverage-inventory.js          # write the report
//   node tools/build-coverage-inventory.js --check   # read-only gate; exit 1 on
//                                                     #   a behavioral gap
// Either mode also exits 1 (writing nothing) if a suite fails during the
// coverage pass — a partial run can't produce a trustworthy inventory or gate.
"use strict";
const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const REPO = path.resolve(__dirname, "..");
const CHECK = process.argv.includes("--check");

// ── Which files hold the surface ────────────────────────────────────────────
// Everything under js/ except vendored builds, per-region data (generated by
// tools/split-data.js), and the monolithic *-data.js manifests.
function listJs(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "vendor" || entry.name === "regions") continue;
      listJs(full, out);
    } else if (entry.name.endsWith(".js") && !entry.name.endsWith("-data.js")) {
      out.push(full);
    }
  }
  return out;
}
const jsFiles = listJs(path.join(REPO, "js")).sort();
const rel = (p) => path.relative(REPO, p).split(path.sep).join("/");

// ── The global surface: top-level functions + window assignments ────────────
// A top-level `function` is one declared at column 0 (not nested, not a method).
// files is the SET of files a name is declared in — 15 names live in two files
// (the provider filters in *-specific.js and form-controls.js, _xlsxWriter,
// _ingestLabel). Coverage must credit execution in ANY declaring file, so we
// keep them all, not just the first.
const surface = new Map(); // name -> { files:Set<rel>, kinds:Set }
const add = (name, file, kind) => {
  if (!surface.has(name))
    surface.set(name, { files: new Set(), kinds: new Set() });
  const info = surface.get(name);
  info.files.add(rel(file));
  info.kinds.add(kind);
};
for (const file of jsFiles) {
  const src = fs.readFileSync(file, "utf8");
  // Top-level function declarations, including `async function` and generators.
  // The `\s+ | \s*\*\s*` alternation requires real separation so `functionfoo(`
  // (a single identifier) is never mistaken for a declaration of `foo`.
  for (const m of src.matchAll(
    /^(?:async\s+)?function(?:\s+|\s*\*\s*)([A-Za-z_$][\w$]*)\s*\(/gm,
  )) {
    add(m[1], file, "function");
  }
  // `=(?!=)` — a single `=` assignment, not the `==`/`===` of a comparison
  // statement (`window.foo === bar;` on its own line would otherwise be counted
  // as a global the site exports).
  for (const m of src.matchAll(/^\s*window\.([A-Za-z_$][\w$]*)\s*=(?!=)/gm)) {
    add(m[1], file, "window");
  }
}

// ── The behavioral surface: names a user can actually reach ──────────────────
const htmlFiles = fs
  .readdirSync(REPO)
  .filter((f) => f.endsWith(".html"))
  .map((f) => path.join(REPO, f));
const allJsSrc = jsFiles.map((f) => fs.readFileSync(f, "utf8")).join("\n");
const allHtmlSrc = htmlFiles.map((f) => fs.readFileSync(f, "utf8")).join("\n");

// JS keywords that follow an on*= in a template literal but are not handlers.
const KEYWORDS = new Set([
  "if",
  "for",
  "while",
  "return",
  "function",
  "switch",
  "this",
]);
const behavioral = new Map(); // name -> Set(reasons)
const markBehavioral = (name, reason) => {
  if (!surface.has(name)) return; // only names that are part of our surface
  if (!behavioral.has(name)) behavioral.set(name, new Set());
  behavioral.get(name).add(reason);
};

// 1. Static handlers on real page elements:  onclick="NAME(
for (const m of allHtmlSrc.matchAll(
  /on[a-z]+=["']\s*([A-Za-z_$][\w$]*)\s*\(/g,
)) {
  markBehavioral(m[1], "html-handler");
}
// 2. Handlers in HTML the app generates as template strings:  onclick=\"NAME(
for (const m of allJsSrc.matchAll(
  /on[a-z]+=\\?["']?\s*([A-Za-z_$][\w$]*)\s*\(/g,
)) {
  if (!KEYWORDS.has(m[1])) markBehavioral(m[1], "generated-handler");
}
// 3. addEventListener(evt, NAME)
for (const m of allJsSrc.matchAll(
  /addEventListener\(\s*["'][a-z]+["']\s*,\s*([A-Za-z_$][\w$]*)/g,
)) {
  markBehavioral(m[1], "event-listener");
}
// 4. Anything named in the worker — it runs on the batch path with no DOM, so a
//    break here silently drops every recommendation to the fallback.
const workerSrc = fs.readFileSync(
  path.join(REPO, "js", "base", "recommendation-worker.js"),
  "utf8",
);
// A surface name can contain `$`, where `\b` is unreliable and `$` is a regex
// anchor — so escape the name and use lookarounds for the identifier boundary.
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
for (const name of surface.keys()) {
  if (name === "recommendationWorker") continue;
  const re = new RegExp(`(?<![\\w$])${escapeRe(name)}(?![\\w$])`);
  if (re.test(workerSrc)) {
    markBehavioral(name, "worker");
  }
}

// ── Coverage: does any suite EXECUTE it? ─────────────────────────────────────
// Source-text ("the name's letters appear in the suite file") counts a comment,
// a string, or an unrelated substring as coverage — it proves the suite mentions
// the name, not that the name's code ever ran. Instead we run each suite under
// V8's coverage collector (NODE_V8_COVERAGE) and read back which functions
// actually executed. vm-loaded app scripts show up in the coverage output keyed
// by the `filename` each suite compiled them with, and V8 infers `functionName`
// for both `function NAME()` declarations and `window.NAME = fn` assignments. So
// a name is covered iff some suite ran a function whose inferred name matches it
// in a file that declares it. Suites pass differing filenames (full repo-
// relative path, bare basename, or none), but basenames are unique across the
// app surface, so we match on basename — which tolerates every convention that
// carries a filename at all.
const suitesDir = path.join(REPO, "tests", "suites");
// Suites are grouped into feature subfolders (ingest/, engine/, …); recurse so
// every one is found wherever it sits.
function findSuites(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) findSuites(full, out);
    else if (entry.name.endsWith("-test.js")) out.push(full);
  }
  return out;
}
const suiteLabels = findSuites(suitesDir)
  .map((f) => path.relative(suitesDir, f).split(path.sep).join("/"))
  .sort();

// Run every suite once under coverage, collecting the set of executed
// `basename::functionName` keys per suite. This is why the tool (and the gate)
// now runs the suites — the report reflects execution reality, not source text,
// and so it can never quietly go stale the way a committed coverage artifact
// could.
function collectExecuted(labels) {
  const covRoot = fs.mkdtempSync(path.join(os.tmpdir(), "cir-cov-"));
  const bySuite = new Map(); // label -> Set("basename::functionName")
  const failed = []; // suites that exited non-zero during the coverage pass
  try {
    for (const label of labels) {
      const dir = path.join(covRoot, label.replace(/[\\/]/g, "__"));
      fs.mkdirSync(dir, { recursive: true });
      const res = spawnSync(process.execPath, [path.join(suitesDir, label)], {
        encoding: "utf8",
        timeout: 120000,
        env: { ...process.env, NODE_V8_COVERAGE: dir },
      });
      const executed = new Set();
      for (const f of fs.readdirSync(dir)) {
        if (!f.endsWith(".json")) continue;
        let cov;
        try {
          cov = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
        } catch {
          continue; // a torn coverage file from a crash — skip it
        }
        for (const script of cov.result || []) {
          if (!script.url) continue;
          const base = path.basename(script.url.replace(/\\/g, "/"));
          for (const fn of script.functions || []) {
            if (!fn.functionName || !fn.ranges.some((r) => r.count > 0))
              continue;
            // V8 infers the name of `function NAME()` as `NAME`, but of
            // `window.NAME = function(){}` (or `= async function`, `= () =>`)
            // as `window.NAME` — the whole assignment target. Our surface keys
            // are bare names, so strip the leading `window.` to match both.
            const nm = fn.functionName.replace(/^window\./, "");
            executed.add(`${base}::${nm}`);
          }
        }
      }
      bySuite.set(label, executed);
      // A crashed suite yields partial or no coverage — enough to under-report a
      // name as uncovered (a written inventory would be wrong) or let the gate
      // pass on data that never fully ran. Record it; the caller aborts before
      // producing any output. run-all.js is the real suite-health gate.
      if (res.status !== 0) failed.push(`${label} (exit ${res.status})`);
    }
  } finally {
    fs.rmSync(covRoot, { recursive: true, force: true });
  }
  return { bySuite, failed };
}
const { bySuite: executedBySuite, failed: failedSuites } =
  collectExecuted(suiteLabels);
// Never write an inventory, nor pass the gate, from a partial coverage run.
// Both modes abort so a red suite can't bake a wrong "uncovered" into the
// committed ledger or let --check pass on data that never fully executed.
if (failedSuites.length) {
  console.error(
    `\nCoverage run aborted: ${failedSuites.length} suite(s) failed during the coverage pass:`,
  );
  for (const f of failedSuites) console.error(`  ${f}`);
  console.error(
    "Coverage from a partial run is unreliable — fix the suite(s) and re-run " +
      "(run-all.js is the suite-health gate).",
  );
  process.exit(1);
}
const coveringSuites = (name) => {
  const keys = [...surface.get(name).files].map(
    (f) => `${path.basename(f)}::${name}`,
  );
  return suiteLabels.filter((label) => {
    const ex = executedBySuite.get(label);
    return keys.some((k) => ex.has(k));
  });
};

// ── Waivers: deliberate non-coverage, each with a reason ─────────────────────
const waiverPath = path.join(REPO, "tests", "coverage-waivers.json");
const waivers = fs.existsSync(waiverPath)
  ? JSON.parse(fs.readFileSync(waiverPath, "utf8"))
  : {};
// Keys starting with "//" are documentation notes, not waivers (JSON has no
// comments), so they never satisfy a name. "//" cannot begin a JS identifier,
// so — unlike an "_" prefix — the note marker can never collide with a real
// global (e.g. _csvMenuOutsideClick, _syncSizeUnit), which must stay waivable.
for (const k of Object.keys(waivers)) if (k.startsWith("//")) delete waivers[k];

// ── Build the rows ───────────────────────────────────────────────────────────
const rows = [...surface.keys()].sort().map((name) => {
  const info = surface.get(name);
  const suites = coveringSuites(name);
  const isBehavioral = behavioral.has(name);
  const waiver = waivers[name];
  let status;
  if (suites.length) status = "covered";
  else if (waiver) status = "waived";
  else status = "uncovered";
  return {
    name,
    file: [...info.files].sort().join(", "),
    kinds: [...info.kinds].join("+"),
    tier: isBehavioral ? "behavioral" : "internal",
    reasons: isBehavioral ? [...behavioral.get(name)].join(", ") : "",
    status,
    suites,
    waiver: waiver || "",
  };
});

// A gap is a behavioral name with no suite and no waiver — the only thing the
// gate fails on. An internal helper may be uncovered; that is a decision, not a
// bug, and the bulk waiver records it.
const gaps = rows.filter(
  (r) => r.tier === "behavioral" && r.status === "uncovered",
);

// ── Emit the report ──────────────────────────────────────────────────────────
const n = (pred) => rows.filter(pred).length;
const lines = [];
lines.push("# Coverage inventory");
lines.push("");
lines.push(
  "Generated by `tools/build-coverage-inventory.js` — do not hand-edit. Run the",
);
lines.push(
  "tool to regenerate after adding or renaming an exported function, a window",
);
lines.push("assignment, a suite, or a waiver.");
lines.push("");
lines.push(
  "**Tier.** _behavioral_ = a name a user reaches (a page handler, a generated",
);
lines.push(
  "handler, an `addEventListener` target, or a name the recommendation worker",
);
lines.push(
  "runs). These MUST be covered or waived — the gate fails otherwise. _internal_",
);
lines.push(
  "= a helper reached only through another function; waivable in bulk, and a bulk",
);
lines.push("waiver still records the reason.");
lines.push("");
lines.push("## Summary");
lines.push("");
lines.push("| | Behavioral | Internal | Total |");
lines.push("| --- | ---: | ---: | ---: |");
lines.push(
  `| Covered | ${n((r) => r.tier === "behavioral" && r.status === "covered")} | ${n((r) => r.tier === "internal" && r.status === "covered")} | ${n((r) => r.status === "covered")} |`,
);
lines.push(
  `| Waived | ${n((r) => r.tier === "behavioral" && r.status === "waived")} | ${n((r) => r.tier === "internal" && r.status === "waived")} | ${n((r) => r.status === "waived")} |`,
);
lines.push(
  `| Uncovered | ${n((r) => r.tier === "behavioral" && r.status === "uncovered")} | ${n((r) => r.tier === "internal" && r.status === "uncovered")} | ${n((r) => r.status === "uncovered")} |`,
);
lines.push(
  `| **Total** | ${n((r) => r.tier === "behavioral")} | ${n((r) => r.tier === "internal")} | ${rows.length} |`,
);
lines.push("");
lines.push(
  gaps.length
    ? `**${gaps.length} behavioral gap(s)** — a user-reachable name with no suite and no waiver. The gate fails on these.`
    : "**No behavioral gaps.** Every user-reachable name is covered or waived.",
);
lines.push("");

if (gaps.length) {
  lines.push("## Behavioral gaps (the gate fails on these)");
  lines.push("");
  lines.push("| Name | File | Reached via |");
  lines.push("| --- | --- | --- |");
  for (const r of gaps)
    lines.push(`| \`${r.name}\` | ${r.file} | ${r.reasons} |`);
  lines.push("");
}

lines.push("## Full surface");
lines.push("");
lines.push("| Name | File | Kind | Tier | Status | Covered by / waiver |");
lines.push("| --- | --- | --- | --- | --- | --- |");
for (const r of rows) {
  const last =
    r.status === "covered"
      ? r.suites.join(", ")
      : r.status === "waived"
        ? `_waived: ${r.waiver}_`
        : "—";
  lines.push(
    `| \`${r.name}\` | ${r.file} | ${r.kinds} | ${r.tier} | ${r.status} | ${last} |`,
  );
}
lines.push("");

const outPath = path.join(REPO, "tests", "coverage-inventory.md");
// --check is a read-only gate: it must not mutate the working tree (a stray
// regen diff would surprise a local run and dirty the tree in CI). Report mode
// writes the committed inventory.
if (!CHECK) {
  fs.writeFileSync(outPath, lines.join("\n"));
  console.log(
    `Wrote ${rel(outPath)} — ${rows.length} names, ${n((r) => r.tier === "behavioral")} behavioral, ${gaps.length} gap(s).`,
  );
} else {
  console.log(
    `Checked ${rows.length} names, ${n((r) => r.tier === "behavioral")} behavioral, ${gaps.length} gap(s).`,
  );
}

if (CHECK && gaps.length) {
  console.error(
    `\nCoverage gate FAILED: ${gaps.length} behavioral name(s) with no suite and no waiver:`,
  );
  for (const r of gaps) console.error(`  ${r.name}  (${r.file}; ${r.reasons})`);
  console.error(
    "\nCover it with a suite, or add it to tests/coverage-waivers.json with a reason.",
  );
  process.exit(1);
}
